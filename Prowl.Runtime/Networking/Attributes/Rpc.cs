using Prowl.Warp;

namespace Prowl.Runtime.Networking;

/// <summary>
///     Remote procedure calls. Mark an instance method on a <see cref="Component" />, or a static method on
///     a non-generic class, with one of the attributes here. Calling it runs it on the peers the attribute
///     names, with the same arguments. The method must
///     return void; its arguments must be types <see cref="NetSerializer{T}" /> supports.
/// </summary>
/// <remarks>
///     Like <see cref="SyncAttribute" />, this is generated by Prowl's script compiler, so it only works in
///     game scripts. Static RPCs support Broadcast and Host, including HostOnly and Unreliable; Owner and
///     OwnerOnly require an object and are rejected. Static RPCs carry arguments without capturing object state.
///     Without a network session an RPC is an ordinary method call.
/// </remarks>
public static partial class Rpc
{
    /// <summary>
    ///     The peer whose call is running right now. Inside an RPC that came over the network, the caller;
    ///     anywhere else, the local peer. Null without a session.
    /// </summary>
    public static NetPeer? Caller => Networking.CurrentCaller ?? Networking.Session?.LocalPeer;

    /// <summary>True while running an RPC that came over the network.</summary>
    public static bool IsRemote => Networking.CurrentCaller != null;
}
