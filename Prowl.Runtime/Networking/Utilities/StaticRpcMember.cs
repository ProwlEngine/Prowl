using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Diagnostics.CodeAnalysis;
using System.IO;
using System.Reflection;

using Prowl.Warp;
using Prowl.Ember;

namespace Prowl.Runtime.Networking;

/// <summary>Generated argument reader for a static RPC. Validation reads arguments without executing the body.</summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public delegate void StaticRpcInvoker(ref NetReader reader, bool execute);

/// <summary>A static RPC descriptor generated by the script compiler. Not meant to be created by hand.</summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public sealed class StaticRpcMember
{
    private static readonly ReloadCache<Type, Dictionary<uint, StaticRpcMember>> s_members = new(Build);
    private readonly StaticRpcInvoker _invoke;

    public StaticRpcMember([DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicFields |
                                                       DynamicallyAccessedMemberTypes.NonPublicFields)]
        Type declaringType, uint id, string signature, RpcMode mode, RpcFlags flags, StaticRpcInvoker invoke)
    {
        if (!declaringType.IsClass || declaringType.ContainsGenericParameters ||
            mode is not (RpcMode.Broadcast or RpcMode.Host) ||
            (flags & RpcFlags.OwnerOnly) != 0)
        {
            throw new ArgumentException("Static RPCs require a non-generic class and cannot use object ownership.");
        }

        DeclaringType = declaringType;
        TypeName = $"{declaringType.FullName}, {declaringType.Assembly.GetName().Name}";
        Id = id;
        Signature = signature;
        Mode = mode;
        Flags = flags;
        _invoke = invoke;
    }

    public Type DeclaringType { get; }
    internal string TypeName { get; }
    public uint Id { get; }
    public string Signature { get; }
    public RpcMode Mode { get; }
    public RpcFlags Flags { get; }

    /// <summary>Generated prologue: false means execute locally; true supplies an argument writer the caller must dispose.</summary>
    public bool Begin(out NetWriter writer)
    {
        writer = null!;
        return Networking.System?.Rpcs.BeginStaticRpc(this, out writer) == true;
    }

    /// <summary>Generated: sends the arguments and returns whether the caller also executes the body.</summary>
    public bool Send(NetWriter writer) => Networking.System?.Rpcs.SendStaticRpc(this, writer) == true;

    /// <summary>Generated: argument decoding finished; subsequent exceptions belong to the RPC body.</summary>
    public static void ArgumentsRead() => Networking.System?.Rpcs.RpcArgumentsRead();

    internal void Invoke(ref NetReader reader) => _invoke(ref reader, true);

    internal void ValidateArguments(ReadOnlySpan<byte> arguments)
    {
        NetReader reader = new(arguments);
        _invoke(ref reader, false);
        if (!reader.IsAtEnd)
        {
            throw new InvalidDataException("Static RPC arguments contain trailing bytes.");
        }
    }

    [UnconditionalSuppressMessage("Trimming", "IL2026",
        Justification =
            "Player builds preserve script assemblies; generated descriptors root their declaring type fields.")]
    internal static StaticRpcMember? Find(string typeName, uint id)
    {
        Type? type = RuntimeUtils.ResolveType(typeName);
        return type is { IsClass: true, ContainsGenericParameters: false }
            ? s_members[type].GetValueOrDefault(id)
            : null;
    }

    [UnconditionalSuppressMessage("Trimming", "IL2070",
        Justification = "Player builds preserve script assemblies and their generated RPC descriptor fields.")]
    private static Dictionary<uint, StaticRpcMember> Build(Type type)
    {
        Dictionary<uint, StaticRpcMember> members = new();
        foreach (FieldInfo field in type.GetFields(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic |
                                                   BindingFlags.DeclaredOnly))
        {
            if (field.FieldType != typeof(StaticRpcMember) || field.GetValue(null) is not StaticRpcMember rpc ||
                rpc.DeclaringType != type)
            {
                continue;
            }

            if (!members.TryAdd(rpc.Id, rpc))
            {
                throw new InvalidOperationException($"Static RPC id collision on {type.FullName}: {rpc.Id}.");
            }
        }

        return members;
    }
}
