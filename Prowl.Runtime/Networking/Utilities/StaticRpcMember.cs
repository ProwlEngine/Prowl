using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Diagnostics.CodeAnalysis;
using System.IO;
using System.Reflection;

using Prowl.Courier;
using Prowl.Ember;

namespace Prowl.Runtime.Networking;

/// <summary>Generated argument reader for a static RPC. Validation reads arguments without executing the body.</summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public delegate void StaticRpcInvoker(ref NetReader reader, bool execute);

/// <summary>A static RPC descriptor generated by the script compiler. Not meant to be created by hand.</summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public sealed class StaticRpcMember
{
    private static readonly ReloadCache<Type, Dictionary<uint, StaticRpcMember>> s_members = new(Build);
    private readonly StaticRpcInvoker _invoke;

    public StaticRpcMember([DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicFields |
                                                       DynamicallyAccessedMemberTypes.NonPublicFields)]
        Type declaringType, uint id, string signature, RpcMode mode, RpcFlags flags, StaticRpcInvoker invoke,
        byte channel = 0)
    {
        if (!declaringType.IsClass || declaringType.ContainsGenericParameters ||
            mode is not (RpcMode.Broadcast or RpcMode.Host))
        {
            throw new ArgumentException("Static RPCs require a non-generic class and cannot use object ownership.");
        }

        DeclaringType = declaringType;
        TypeName = NameOf(declaringType);
        TypeHash = Hash(TypeName);
        Id = id;
        Signature = signature;
        Mode = mode;
        Flags = flags;
        Channel = channel;
        _invoke = invoke;
    }

    public Type DeclaringType { get; }
    internal string TypeName { get; }

    /// <summary>What a call names the declaring type by: a hash of its name and its assembly's.</summary>
    internal uint TypeHash { get; }
    public uint Id { get; }
    public string Signature { get; }
    public RpcMode Mode { get; }
    public RpcFlags Flags { get; }

    /// <summary>The transport channel calls travel on.</summary>
    public byte Channel { get; }

    /// <summary>Generated prologue: false means execute locally; true supplies an argument writer the caller must dispose.</summary>
    public bool Begin(out NetWriter writer)
    {
        writer = null!;
        return Networking.System?.Rpcs.BeginStaticRpc(this, out writer) == true;
    }

    /// <summary>Generated: sends the arguments and returns whether the caller also executes the body.</summary>
    public bool Send(NetWriter writer) => Networking.System?.Rpcs.SendStaticRpc(this, writer) == true;

    /// <summary>Generated: argument decoding finished; subsequent exceptions belong to the RPC body.</summary>
    public static void ArgumentsRead() => Networking.System?.Rpcs.RpcArgumentsRead();

    internal void Invoke(ref NetReader reader) => _invoke(ref reader, true);

    internal void ValidateArguments(ReadOnlySpan<byte> arguments)
    {
        NetReader reader = new(arguments);
        _invoke(ref reader, false);
        if (!reader.IsAtEnd)
        {
            throw new InvalidDataException("Static RPC arguments contain trailing bytes.");
        }
    }

    private static string NameOf(Type type) => $"{type.FullName}, {type.Assembly.GetName().Name}";

    private static uint Hash(string name)
    {
        uint hash = 2166136261;
        foreach (char c in name)
        {
            hash = (hash ^ c) * 16777619;
        }

        return hash;
    }

    /// <summary>The hash calls name <paramref name="type" /> by.</summary>
    internal static uint HashOf(Type type) => Hash(NameOf(type));

    // The types that declare static RPCs by hash, with the number of assemblies it was built from.
    private static readonly ReloadCache<bool, (Dictionary<uint, Type> Types, int Assemblies)> s_types = new();

    internal static StaticRpcMember? Find(uint typeHash, uint id)
    {
        int assemblies = 0;
        foreach (Assembly _ in RuntimeUtils.AssemblySource())
        {
            assemblies++;
        }

        // Rebuilt only when assemblies came or went, so calls naming unknown types cost one lookup.
        if (!s_types.TryGetValue(true, out (Dictionary<uint, Type> Types, int Assemblies) known) ||
            known.Assemblies != assemblies)
        {
            known = (BuildTypes(), assemblies);
            s_types.Set(true, known);
        }

        return known.Types.TryGetValue(typeHash, out Type? type) ? s_members[type].GetValueOrDefault(id) : null;
    }

    [UnconditionalSuppressMessage("Trimming", "IL2026",
        Justification =
            "Player builds preserve script assemblies; generated descriptors root their declaring type fields.")]
    [UnconditionalSuppressMessage("Trimming", "IL2075",
        Justification = "Player builds preserve script assemblies and their generated RPC descriptor fields.")]
    private static Dictionary<uint, Type> BuildTypes()
    {
        string runtime = typeof(Component).Assembly.GetName().Name!;
        Dictionary<uint, Type> types = new();
        HashSet<uint> collided = new();
        HashSet<string> seen = new(StringComparer.OrdinalIgnoreCase);
        foreach (Assembly assembly in RuntimeUtils.AssemblySource())
        {
            // The live build comes first, so a later assembly by the same name is a superseded one.
            string name = assembly.GetName().Name ?? "";
            if (!seen.Add(name) || assembly.IsDynamic ||
                (name != runtime && !Array.Exists(assembly.GetReferencedAssemblies(), a => a.Name == runtime)))
            {
                continue;
            }

            Type[] found;
            try
            {
                found = assembly.GetTypes();
            }
            catch (ReflectionTypeLoadException e)
            {
                found = Array.FindAll(e.Types, t => t != null)!;
            }

            foreach (Type type in found)
            {
                if (!type.IsClass || type.ContainsGenericParameters || !DeclaresStaticRpcs(type))
                {
                    continue;
                }

                // Two types under one id can't be told apart, so neither takes calls.
                uint hash = HashOf(type);
                if (collided.Contains(hash))
                {
                    Debug.LogError(
                        $"[Network] {NameOf(type)} hashes to a static RPC type id other types have too, so calls to " +
                        "it are dropped. Rename it.");
                }
                else if (!types.TryAdd(hash, type))
                {
                    Debug.LogError(
                        $"[Network] {NameOf(type)} and {NameOf(types[hash])} hash to the same static RPC type id, so " +
                        "calls to both are dropped. Rename one of them.");
                    types.Remove(hash);
                    collided.Add(hash);
                }
            }
        }

        return types;
    }

    [UnconditionalSuppressMessage("Trimming", "IL2070",
        Justification = "Player builds preserve script assemblies and their generated RPC descriptor fields.")]
    private static bool DeclaresStaticRpcs(Type type)
    {
        foreach (FieldInfo field in type.GetFields(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic |
                                                   BindingFlags.DeclaredOnly))
        {
            if (field.FieldType == typeof(StaticRpcMember))
            {
                return true;
            }
        }

        return false;
    }

    [UnconditionalSuppressMessage("Trimming", "IL2070",
        Justification = "Player builds preserve script assemblies and their generated RPC descriptor fields.")]
    private static Dictionary<uint, StaticRpcMember> Build(Type type)
    {
        Dictionary<uint, StaticRpcMember> members = new();
        foreach (FieldInfo field in type.GetFields(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic |
                                                   BindingFlags.DeclaredOnly))
        {
            if (field.FieldType != typeof(StaticRpcMember) || field.GetValue(null) is not StaticRpcMember rpc ||
                rpc.DeclaringType != type)
            {
                continue;
            }

            if (!members.TryAdd(rpc.Id, rpc))
            {
                throw new InvalidOperationException($"Static RPC id collision on {type.FullName}: {rpc.Id}.");
            }
        }

        return members;
    }
}
