using System;

using Prowl.Warp;

namespace Prowl.Runtime.Networking;

/// <summary>Describes how a <see cref="SyncAttribute"/> property is synchronized.</summary>
[Flags]
public enum SyncFlags : uint
{
    None = 0,

    /// <summary>Only the host may change the value, even on an object a client owns.</summary>
    FromHost = 1,
}

/// <summary>
/// Keeps a property of a <see cref="Component"/> the same on every peer. Whoever controls the object
/// (its owner, or the host) sets it; everyone else receives the new value at the next network tick,
/// and setting it there is ignored. Late joiners get the current value.
/// </summary>
/// <remarks>
/// Write it on an auto-property, as in <c>[Sync] public int Health { get; set; } = 100;</c>. Prowl's
/// script compiler generates the networking around it, so it only works in game scripts. Without a
/// network session the property behaves like any other.
/// </remarks>
[AttributeUsage(AttributeTargets.Property)]
public sealed class SyncAttribute : Attribute
{
    public SyncAttribute() { }

    public SyncAttribute(SyncFlags flags) => Flags = flags;

    public SyncFlags Flags { get; set; }
}

/// <summary>Who runs an RPC.</summary>
public enum RpcMode : byte
{
    /// <summary>Everyone, the caller included.</summary>
    Broadcast,

    /// <summary>The host only.</summary>
    Host,

    /// <summary>Whoever controls the object: its owner, or the host when it has none.</summary>
    Owner,
}

/// <summary>Options for an RPC.</summary>
[Flags]
public enum RpcFlags : uint
{
    None = 0,

    /// <summary>Send it unreliably: cheaper and lower latency, but it may be lost. Arguments must fit in one packet.</summary>
    Unreliable = 1,

    /// <summary>Only the host may call it. Calls from clients are dropped.</summary>
    HostOnly = 2,

    /// <summary>Only whoever controls the object may call it. Calls from anyone else are dropped.</summary>
    OwnerOnly = 4,
}

/// <summary>
/// Remote procedure calls. Mark a method on a <see cref="Component"/> with one of the attributes here
/// and calling it runs it on the peers the attribute names, with the same arguments. The method must
/// return void; its arguments must be types <see cref="NetSerializer{T}"/> supports.
/// </summary>
/// <remarks>
/// Like <see cref="SyncAttribute"/>, this is generated by Prowl's script compiler, so it only works in
/// game scripts. Without a network session an RPC is an ordinary method call.
/// </remarks>
public static class Rpc
{
    /// <summary>
    /// The peer whose call is running right now. Inside an RPC that came over the network, the caller;
    /// anywhere else, the local peer. Null without a session.
    /// </summary>
    public static NetPeer? Caller => Networking.CurrentCaller ?? Networking.Session?.LocalPeer;

    /// <summary>True while running an RPC that came over the network.</summary>
    public static bool IsRemote => Networking.CurrentCaller != null;

    /// <summary>Base for the RPC attributes.</summary>
    [AttributeUsage(AttributeTargets.Method)]
    public abstract class RpcAttribute : Attribute
    {
        private protected RpcAttribute(RpcMode mode, RpcFlags flags)
        {
            Mode = mode;
            Flags = flags;
        }

        public RpcMode Mode { get; }

        public RpcFlags Flags { get; }
    }

    /// <summary>Runs on everyone, the caller included.</summary>
    public sealed class BroadcastAttribute(RpcFlags flags = RpcFlags.None) : RpcAttribute(RpcMode.Broadcast, flags);

    /// <summary>Runs on the host only.</summary>
    public sealed class HostAttribute(RpcFlags flags = RpcFlags.None) : RpcAttribute(RpcMode.Host, flags);

    /// <summary>Runs on whoever controls the object: its owner, or the host when it has none.</summary>
    public sealed class OwnerAttribute(RpcFlags flags = RpcFlags.None) : RpcAttribute(RpcMode.Owner, flags);
}
